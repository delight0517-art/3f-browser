#!/bin/bash
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
app_bundle="${1:?Usage: package-3f-cef-host.sh /path/to/3F Browser.app}"
cefclient="$repo_root/.build/cef-156-arm64/cefsimple-isolated-build/tests/cefclient/Release/cefclient.app"
destination="$(dirname "$app_bundle")/3F Chromium Browser.app"
previous_nested="$app_bundle/Contents/Helpers/3F Chromium Browser.app"

if [[ ! -d "$cefclient" ]]; then
  echo "Missing signed CEF browser host: $cefclient" >&2
  exit 2
fi
if [[ ! -d "$app_bundle/Contents/Resources" || ! -f "$app_bundle/Contents/Info.plist" ]]; then
  echo "Target must be a packaged 3F Browser.app: $app_bundle" >&2
  exit 3
fi

mkdir -p "$(dirname "$destination")"
rm -rf "$destination"
ditto "$cefclient" "$destination"
/usr/libexec/PlistBuddy -c 'Set :CFBundleName 3F Chromium Browser' "$destination/Contents/Info.plist"
/usr/libexec/PlistBuddy -c 'Add :CFBundleDisplayName string 3F Chromium Browser' "$destination/Contents/Info.plist" 2>/dev/null \
  || /usr/libexec/PlistBuddy -c 'Set :CFBundleDisplayName 3F Chromium Browser' "$destination/Contents/Info.plist"
cp "$app_bundle/Contents/Resources/3f-icon.icns" "$destination/Contents/Resources/cefclient.icns"

# CEF's macOS browser process must be a standalone app bundle. Retire only the
# obsolete nested host generated by this package script.
if [[ -d "$previous_nested" ]]; then
  rm -rf "$previous_nested"
fi

# Preserve the bundle identifiers used by CEF to locate its subprocesses; only
# change the user-facing name and icon when placing the host inside 3F.
codesign --force --deep --sign - "$destination"
codesign --verify --deep --strict "$destination"
printf 'Bundled 3F Chromium browser host: %s\n' "$destination"
